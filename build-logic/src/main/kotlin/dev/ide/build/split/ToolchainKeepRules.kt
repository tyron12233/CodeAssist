package dev.ide.build.split

import org.objectweb.asm.ClassReader
import org.objectweb.asm.ClassVisitor
import org.objectweb.asm.FieldVisitor
import org.objectweb.asm.Handle
import org.objectweb.asm.MethodVisitor
import org.objectweb.asm.Opcodes
import org.objectweb.asm.Type

/**
 * Keep rules for the members of R8's program that the toolchain uses.
 *
 * The toolchain (the Kotlin compiler, IntelliJ, JDT, ...) is not R8 input: R8 sees it on its classpath and
 * never rewrites it. But it calls into classes that ARE R8 input (kotlin-stdlib, guava, coroutines, ...), and
 * R8 cannot see those calls, so without these rules it would rename or remove whatever only the toolchain
 * uses. This walks every toolchain class and keeps, in the program, exactly what it names: each referenced
 * class, each field and method it accesses (on the program class that declares it), and each method a
 * toolchain class overrides from a program supertype.
 */
class ToolchainKeepRules(private val program: Map<String, ProgramClass>) {

    /** What the generator needs to know about one program class. */
    class ProgramClass(
        val superName: String?,
        val interfaces: List<String>,
        val fields: Set<String>,   // name + ":" + descriptor
        val methods: Set<String>,  // name + descriptor
    )

    private val keptClasses = sortedSetOf<String>()
    private val keptMembers = sortedMapOf<String, MutableSet<String>>()

    /** Records everything the toolchain class [bytes] references in the program. */
    fun scan(bytes: ByteArray) {
        val reader = ClassReader(bytes)
        reader.accept(Collector(), ClassReader.SKIP_FRAMES)
    }

    /** The rules, one `-keep` per program class the toolchain reaches. */
    fun render(): String = buildString {
        appendLine("# Generated by dev.ide.toolchain-split: program members the pre-dexed toolchain uses.")
        appendLine("# The toolchain is on R8's classpath, not in its program, so R8 cannot see these uses.")
        for (cls in keptClasses) {
            val members = keptMembers[cls].orEmpty()
            val javaName = cls.replace('/', '.')
            if (members.isEmpty()) {
                appendLine("-keep class $javaName")
            } else {
                appendLine("-keep class $javaName {")
                for (m in members) appendLine("    $m;")
                appendLine("}")
            }
        }
    }

    val classCount: Int get() = keptClasses.size
    val memberCount: Int get() = keptMembers.values.sumOf { it.size }

    private fun keepClass(internalName: String) {
        val name = elementClass(internalName) ?: return
        if (name in program) keptClasses += name
    }

    private fun keepType(type: Type) {
        when (type.sort) {
            Type.OBJECT -> keepClass(type.internalName)
            Type.ARRAY -> keepType(type.elementType)
            Type.METHOD -> {
                keepType(type.returnType)
                type.argumentTypes.forEach(::keepType)
            }
        }
    }

    private fun keepDescriptor(descriptor: String) = keepType(Type.getType(descriptor))

    /** Keeps the field [name]:[desc] on the program class in [owner]'s hierarchy that declares it. */
    private fun keepField(owner: String, name: String, desc: String) {
        keepClass(owner)
        val declaring = findDeclaring(owner) { "$name:$desc" in it.fields } ?: return
        member(declaring, "${javaType(Type.getType(desc))} $name")
    }

    /** Keeps the method [name][desc] on the program class in [owner]'s hierarchy that declares it. */
    private fun keepMethod(owner: String, name: String, desc: String) {
        keepClass(owner)
        val declaring = findDeclaring(owner) { "$name$desc" in it.methods } ?: return
        member(declaring, methodRule(name, desc))
    }

    private fun member(cls: String, rule: String) {
        keptClasses += cls
        keptMembers.getOrPut(cls) { sortedSetOf() } += rule
    }

    /** Breadth-first through supertypes that are program classes, so a library supertype ends the search. */
    private fun findDeclaring(start: String, declares: (ProgramClass) -> Boolean): String? {
        val queue = ArrayDeque(listOf(start))
        val seen = HashSet<String>()
        while (queue.isNotEmpty()) {
            val name = queue.removeFirst()
            if (!seen.add(name)) continue
            val cls = program[name] ?: continue
            if (declares(cls)) return name
            cls.superName?.let(queue::addLast)
            queue.addAll(cls.interfaces)
        }
        return null
    }

    private inner class Collector : ClassVisitor(Opcodes.ASM9) {
        private val supertypes = ArrayList<String>()

        override fun visit(version: Int, access: Int, name: String, signature: String?, superName: String?, interfaces: Array<out String>?) {
            superName?.let { supertypes += it; keepClass(it) }
            interfaces?.forEach { supertypes += it; keepClass(it) }
        }

        override fun visitField(access: Int, name: String, descriptor: String, signature: String?, value: Any?): FieldVisitor? {
            keepDescriptor(descriptor)
            return null
        }

        override fun visitMethod(access: Int, name: String, descriptor: String, signature: String?, exceptions: Array<out String>?): MethodVisitor {
            keepDescriptor(descriptor)
            exceptions?.forEach(::keepClass)
            // An override of a program supertype's method: R8 must keep that method's name and signature, or
            // calls through the supertype stop reaching this class.
            if (name != "<init>" && name != "<clinit>" && access and Opcodes.ACC_STATIC == 0) {
                for (s in supertypes) {
                    val declaring = findDeclaring(s) { "$name$descriptor" in it.methods } ?: continue
                    member(declaring, methodRule(name, descriptor))
                }
            }
            return object : MethodVisitor(Opcodes.ASM9) {
                override fun visitTypeInsn(opcode: Int, type: String) = keepClass(type)
                override fun visitFieldInsn(opcode: Int, owner: String, name: String, descriptor: String) =
                    keepField(owner, name, descriptor)
                override fun visitMethodInsn(opcode: Int, owner: String, name: String, descriptor: String, isInterface: Boolean) =
                    keepMethod(owner, name, descriptor)
                override fun visitInvokeDynamicInsn(name: String, descriptor: String, bsm: Handle, vararg args: Any?) {
                    keepDescriptor(descriptor)
                    keepHandle(bsm)
                    args.forEach(::keepConstant)
                }
                override fun visitLdcInsn(value: Any?) = keepConstant(value)
                override fun visitMultiANewArrayInsn(descriptor: String, numDimensions: Int) = keepDescriptor(descriptor)
                override fun visitTryCatchBlock(start: org.objectweb.asm.Label, end: org.objectweb.asm.Label, handler: org.objectweb.asm.Label, type: String?) {
                    type?.let(::keepClass)
                }
            }
        }

        private fun keepHandle(h: Handle) {
            if (h.tag <= Opcodes.H_PUTSTATIC) keepField(h.owner, h.name, h.desc) else keepMethod(h.owner, h.name, h.desc)
        }

        private fun keepConstant(value: Any?) {
            when (value) {
                is Type -> keepType(value)
                is Handle -> keepHandle(value)
            }
        }
    }

    companion object {
        /** The class an internal name or array descriptor names, or null for a primitive array. */
        fun elementClass(internalName: String): String? =
            if (internalName.startsWith("[")) Type.getType(internalName).elementType.takeIf { it.sort == Type.OBJECT }?.internalName
            else internalName

        fun javaType(t: Type): String = when (t.sort) {
            Type.ARRAY -> javaType(t.elementType) + "[]".repeat(t.dimensions)
            else -> t.className
        }

        fun methodRule(name: String, desc: String): String {
            val t = Type.getMethodType(desc)
            val args = t.argumentTypes.joinToString(",") { javaType(it) }
            return if (name == "<init>") "<init>($args)" else "${javaType(t.returnType)} $name($args)"
        }
    }
}

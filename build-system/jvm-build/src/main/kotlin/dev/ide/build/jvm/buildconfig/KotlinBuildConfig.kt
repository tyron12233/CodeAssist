package dev.ide.build.jvm.buildconfig

import dev.ide.model.Facet
import dev.ide.model.FacetCodec
import dev.ide.model.FacetKey

/**
 * A module's generated Kotlin `BuildConfig` object, as the `[kotlinBuildConfig]` table of `module.toml`: what the
 * `com.github.gmazzo.buildconfig` Gradle plugin produces, which is how Kotlin Multiplatform and JVM projects get
 * build-time constants (Android modules use AGP's own `BuildConfig`, see `AndroidFacet.buildConfigFields`).
 *
 * The plugin writes `[packageName].[className]` as an object of `const val`s; [KotlinBuildConfigPlugin] does the
 * same before the module compiles.
 */
data class KotlinBuildConfigFacet(
    val packageName: String,
    val className: String = "BuildConfig",
    /** The plugin's Kotlin output is `internal` by default; `public` when the script turns that off. */
    val internalVisibility: Boolean = true,
    val fields: List<Field> = emptyList(),
) : Facet {
    override val key: FacetKey<KotlinBuildConfigFacet> get() = KEY

    /** One constant: its Kotlin [type] (`String`, `Int`, `Boolean`, …), [name], and the Kotlin expression [value]. */
    data class Field(val type: String, val name: String, val value: String) {
        fun encode(): String = "$type $name = $value"

        companion object {
            private val FORM = Regex("""^\s*(\S+)\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$""", RegexOption.DOT_MATCHES_ALL)
            fun decode(text: String): Field? = FORM.find(text)?.let { Field(it.groupValues[1], it.groupValues[2], it.groupValues[3]) }
        }
    }

    companion object {
        val KEY = FacetKey<KotlinBuildConfigFacet>("kotlinBuildConfig")

        /** Where the object is generated, relative to the module: a SOURCE root the importer declares (and, for a
         *  multiplatform module, a common one, so `commonMain` code can read it). */
        const val GENERATED_KOTLIN_ROOT: String = "build/build-config/kotlin"
    }
}

object KotlinBuildConfigFacetCodec : FacetCodec<KotlinBuildConfigFacet> {
    override val key get() = KotlinBuildConfigFacet.KEY
    override val tomlTable = "kotlinBuildConfig"

    override fun encode(facet: KotlinBuildConfigFacet): Map<String, Any?> = buildMap {
        put("package", facet.packageName)
        if (facet.className != "BuildConfig") put("className", facet.className)
        if (!facet.internalVisibility) put("internal", false)
        put("fields", facet.fields.map { it.encode() })
    }

    override fun decode(values: Map<String, Any?>): KotlinBuildConfigFacet = KotlinBuildConfigFacet(
        packageName = values["package"] as? String ?: "",
        className = values["className"] as? String ?: "BuildConfig",
        internalVisibility = values["internal"] as? Boolean ?: true,
        fields = (values["fields"] as? List<*>).orEmpty().mapNotNull { (it as? String)?.let(KotlinBuildConfigFacet.Field::decode) },
    )
}

/** The Kotlin source the plugin writes for [facet]. */
object KotlinBuildConfigSource {
    fun render(facet: KotlinBuildConfigFacet): String = buildString {
        val visibility = if (facet.internalVisibility) "internal" else "public"
        if (facet.packageName.isNotBlank()) appendLine("package ${facet.packageName}").appendLine()
        appendLine("// Generated by CodeAssist from the module's buildConfig { } block. Do not edit.")
        appendLine("$visibility object ${facet.className} {")
        for (f in facet.fields) {
            // `const` only where Kotlin allows it: primitives and String with a constant initializer.
            val const = if (f.type in CONST_TYPES) "const " else ""
            appendLine("  $visibility ${const}val ${f.name}: ${f.type} = ${f.value}")
        }
        appendLine("}")
    }

    private val CONST_TYPES = setOf("String", "Int", "Long", "Boolean", "Float", "Double", "Short", "Byte", "Char")
}

import org.jetbrains.kotlin.gradle.ExperimentalWasmDsl
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// playground-spike (EXPERIMENTAL): the whole browser Playground pipeline with no JVM at run time.
//
//   source text --parse, lower (wasm: :lang-kotlin)--> PreviewWire blob
//               --interpret (inside :jvm-vm, which runs :interp-core from its jars)--> program output
//
// The wasm target is the product. The jvm target exists only to resolve the JVM jars the VM interprets
// (:interp-core and what it needs), so the test can write their paths into a generated source, the way
// :jvm-vm does for its own fixtures. Depended on by nothing.
plugins {
    alias(libs.plugins.kotlin.multiplatform)
}

kotlin {
    jvm {
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
    }

    @OptIn(ExperimentalWasmDsl::class)
    wasmJs {
        nodejs()      // the tests
        browser()     // the Playground worker
        binaries.executable()
    }

    sourceSets {
        commonMain.dependencies {
            api(project(":lang-kotlin"))
            api(project(":jvm-vm"))
            implementation(project(":index-impl"))
            implementation(libs.kotlinx.coroutines.core)
            implementation(project(":kotlin-classfile"))
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotlinx.coroutines.test)
        }
        jvmMain.dependencies {
            // The code the VM interprets. JVM-only, and never linked into the wasm binary.
            implementation(project(":interp-core"))
        }
    }
}

// The jars the VM interprets: an ALLOWLIST. :lang-kotlin's JVM half drags in the Kotlin compiler, the IntelliJ
// platform, guava, jna and more through its build adapters; the interpreter and the lowered-tree codec reach
// none of that, it is most of the bytes, and every jar is copied into the browser's file system.
val vmJar = Regex("^(kotlin-stdlib|kotlinx-coroutines-core-jvm|kotlinx-collections-immutable-jvm|annotations|syntax-api-jvm|interp-core|lang-kotlin(-index)?-jvm|kotlin-syntax-jvm|kotlin-classfile-jvm|language-api-jvm|model-api-jvm|platform-core-jvm|project-model-api-jvm|vfs-api-jvm)-")
// A lazy filtered FileCollection, not a resolved list: it carries the jar tasks of the project jars with it.
val vmJars: FileCollection = configurations.getByName("jvmRuntimeClasspath").filter { it.isFile && vmJar.containsMatchIn(it.name) }

// The tests' class path: absolute host paths, written into a source the wasm tests read.
val generateVmClasspath by tasks.registering {
    inputs.files(vmJars)
    val out = layout.buildDirectory.dir("generated/vmClasspath/kotlin")
    outputs.dir(out)
    doLast {
        val file = out.get().file("dev/ide/playground/VmClasspath.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(buildString {
            appendLine("package dev.ide.playground")
            appendLine()
            appendLine("/** Generated by :playground-spike's build: the jars the VM interprets. */")
            appendLine("internal object VmClasspath {")
            appendLine("    val entries: List<String> = listOf(")
            for (e in vmJars.files.sortedBy { it.name }) appendLine("        \"${e.absolutePath.replace("\\", "/")}\",")
            appendLine("    )")
            appendLine("}")
        })
    }
}
kotlin.sourceSets.named("wasmJsTest") { kotlin.srcDir(generateVmClasspath) }

// The servable Playground: the page, the worker (compiled Kotlin/Wasm), and the jars the worker fetches.
//   ./gradlew :playground-spike:assemblePlayground      ->  build/playground-web/
// The editor (CodeMirror) bundled into one script with esbuild. Needs node + npm on the machine, as the wasm
// tests already do.
val bundleEditor by tasks.registering(Exec::class) {
    val dir = file("src/web-editor")
    workingDir = dir
    inputs.files(fileTree(dir) { exclude("node_modules/**") }).withPropertyName("editorSources")
    outputs.file(layout.buildDirectory.file("editor-bundle/editor.js"))
    commandLine("sh", "-c", "npm install --no-audit --no-fund --silent && npm run build --silent")
}

val assemblePlayground by tasks.registering(Sync::class) {
    dependsOn("compileProductionExecutableKotlinWasmJs", bundleEditor)
    from(layout.buildDirectory.dir("editor-bundle"))
    into(layout.buildDirectory.dir("playground-web"))
    from("src/web")
    from(layout.buildDirectory.dir("compileSync/wasmJs/main/productionExecutable/kotlin")) {
        include("*.mjs", "*.wasm")
        into("worker")
    }
    from(vmJars) { into("jars") }
    doLast {
        val jars = destinationDir.resolve("jars")
        val names = jars.listFiles { f -> f.name.endsWith(".jar") }!!.map { it.name }.sorted()
        jars.resolve("manifest.json").writeText(names.joinToString(",", "[", "]") { "\"$it\"" })
    }
}

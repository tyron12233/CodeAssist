package dev.ide.lang.java.resolve

import com.intellij.psi.PsiClass
import com.intellij.psi.PsiCompiledElement
import com.intellij.psi.PsiElement
import com.intellij.psi.PsiMethod
import com.intellij.psi.impl.compiled.ClsParameterImpl
import dev.ide.lang.resolve.SourceDocProvider

/**
 * Parameter names and javadoc for a COMPILED (classpath) method or class, which the PSI cannot give: a class
 * file carries no javadoc, and an abstract or interface method keeps no parameter names (the PSI makes up
 * `p`, `p1`, ...). The host's [SourceDocProvider] answers instead: attached sources, the source-doc index,
 * and on an Android module the bundled platform docs. Source PSI answers for itself and is never consulted.
 */
internal class JavaLibraryDocs(private val provider: () -> SourceDocProvider) {

    /** [m]'s parameter names, with the PSI's made-up ones replaced by real names when the provider has them. */
    fun paramNames(m: PsiMethod): List<String> {
        val params = m.parameterList.parameters
        val names = params.map { it.name }
        if (m !is PsiCompiledElement || params.none { it.isMadeUp() }) return names
        val real = lookup(m)?.names?.takeIf { it.size == params.size } ?: return names
        return params.mapIndexed { i, p -> if (p.isMadeUp()) real[i] else names[i] }
    }

    /** The raw javadoc of a compiled method or class, or null (for source PSI, read its own comment). */
    fun rawDoc(target: PsiElement): String? {
        if (target !is PsiCompiledElement) return null
        val p = provider()
        return when (target) {
            is PsiMethod -> owner(target)?.let { p.methodRaw(it, memberName(target), target.parameterList.parametersCount) }
            is PsiClass -> target.qualifiedName?.let(p::classDocRaw)
            else -> null
        }
    }

    /** A compiled method's javadoc as plain text, for the signature and completion panels. */
    fun plainDoc(m: PsiMethod): String? = if (m is PsiCompiledElement) lookup(m)?.doc?.takeIf { it.isNotBlank() } else null

    private fun lookup(m: PsiMethod): SourceDocProvider.MethodDoc? =
        owner(m)?.let { provider().method(it, memberName(m), m.parameterList.parametersCount) }

    private fun owner(m: PsiMethod): String? = m.containingClass?.qualifiedName

    /** Constructors are keyed by the class's simple name, as the bytecode symbol and the source index name them. */
    private fun memberName(m: PsiMethod): String = if (m.isConstructor) m.containingClass?.name ?: m.name else m.name

    private fun com.intellij.psi.PsiParameter.isMadeUp(): Boolean = (this as? ClsParameterImpl)?.isAutoGeneratedName == true
}
